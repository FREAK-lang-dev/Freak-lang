"""Link V4 LLVM modules for wasm32-unknown-wasip1 (the Web lane, W2/W3).

A wasm module links the V4 core runtime (the same C files the native link
uses, minus the V3 monolith), FREAK's own WASI preview 1 platform layer
(freakc/runtime/wasi) and one generated translation unit holding the parts of
the V3 runtime that V4 code still calls: the owned-word registry, the byte
word table, freak_word_to_int and the Shared<T> boxes. Those parts are
extracted from freak_runtime.c / freak_llvm_runtime.c at build time rather
than copied, so the two targets cannot drift; an extraction that no longer
finds its anchors fails the build loudly.

No wasi-libc or sysroot is used: the runtime is built freestanding against
the headers in freakc/runtime/wasi/include, and the module is linked with
clang -nostdlib (wasm-ld). The result runs under any WASI preview 1 host and
in browsers through a small WASI shim (wasm/run_wasi.mjs is the Node runner).
"""
from __future__ import annotations

import hashlib
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

V4_ROOT = Path(__file__).resolve().parent
ROOT = V4_ROOT.parents[2]
RUNTIME_ROOT = ROOT / "freakc" / "runtime"
WASI_ROOT = RUNTIME_ROOT / "wasi"

sys.path.insert(0, str(ROOT / "freakc"))
from v4_native_runtime import SOURCE_NAMES  # noqa: E402

TRIPLE = "wasm32-unknown-wasip1"
# 1 MiB of linear memory is reserved for the shadow stack.
STACK_BYTES = 1 << 20

# The V4 core runtime: every native runtime source except the two V3-era
# files, whose V4-facing parts are extracted below.
CORE_SOURCES = (
    "freak_v4_word_runtime.c",
    "freak_v4_compiler_array_runtime.c",
    "freak_v4_numeric_runtime.c",
    "freak_v4_unicode_runtime.c",
    "freak_v4_system_runtime.c",
    "freak_v4_panic_runtime.c",
)
PLATFORM_SOURCES = ("wasi/freak_v4_pal_wasi.c",)

# (file, first line, signature of the last function). A region runs from the
# line starting with `first` through the column-0 `}` that closes the last
# function; a lone function uses its own signature for both.
EXTRACTS = (
    ("freak_runtime.c", "static const char* freak_word_byte_literal(", "static const char* freak_word_byte_literal("),
    ("freak_runtime.c", "int64_t freak_word_to_int(freak_word w) {", "int64_t freak_word_to_int(freak_word w) {"),
    ("freak_runtime.c", "typedef struct freak_llvm_owned_word {", "void freak_llvm_word_release_assigned("),
    ("freak_llvm_runtime.c", "/* ── V4 Shared<T> / Weak<T>", "void freak_v4_shared_end_write("),
)

C_FLAGS = (
    f"--target={TRIPLE}", "-Oz", "-ffreestanding", "-fno-builtin", "-nostdlibinc",
    "-ffunction-sections", "-fdata-sections", "-w",
)

for _name in CORE_SOURCES:
    if _name not in SOURCE_NAMES:
        raise RuntimeError(f"wasm core runtime source is not in the native runtime inventory: {_name}")


def _region(text: str, first: str, last: str, name: str) -> str:
    lines = text.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.startswith(first)]
    if len(starts) != 1:
        raise RuntimeError(f"wasm runtime extraction: {name} has {len(starts)} lines starting with {first!r}")
    ends = [i for i, line in enumerate(lines) if line.startswith(last) and i >= starts[0]]
    if not ends:
        raise RuntimeError(f"wasm runtime extraction: {name} has no {last!r} after {first!r}")
    close = next((i for i in range(ends[0], len(lines)) if lines[i].rstrip("\r\n") == "}"), None)
    if close is None:
        raise RuntimeError(f"wasm runtime extraction: {last!r} in {name} never closes")
    return "".join(lines[starts[0]:close + 1])


def extracted_source(runtime_root: Path = RUNTIME_ROOT) -> str:
    parts = [
        "/* Generated by src/compiler/v4/wasm_target.py: V4-facing parts of the\n"
        "   V3 runtime, extracted verbatim for the wasm32 runtime. */\n",
        '#include "wasi/freak_v4_wasm_glue.c"\n',
        "#include <stdatomic.h>\n",
    ]
    for name, first, last in EXTRACTS:
        text = (runtime_root / name).read_text(encoding="utf-8")
        parts.append(f"\n/* ---- {name}: {first.strip()} ---- */\n")
        parts.append(_region(text, first, last, name))
    return "".join(parts)


def _clang_identity(clang: str) -> str:
    result = subprocess.run([clang, "--version"], capture_output=True, text=True, timeout=30)
    return result.stdout.splitlines()[0] if result.returncode == 0 and result.stdout else clang


def _run(command: list[str], label: str) -> None:
    result = subprocess.run(command, capture_output=True, text=True, timeout=300)
    if result.returncode != 0:
        raise RuntimeError(f"{label} failed:\n{' '.join(command)}\n{result.stdout}{result.stderr}")


def runtime_objects(clang: str, cache_root: Path) -> list[Path]:
    """Compile (or reuse) the wasm runtime objects for this clang."""
    generated = extracted_source()
    sources = [(name, (RUNTIME_ROOT / name).read_bytes()) for name in CORE_SOURCES + PLATFORM_SOURCES]
    digest = hashlib.sha256()
    digest.update(_clang_identity(clang).encode())
    digest.update(" ".join(C_FLAGS).encode())
    digest.update(generated.encode())
    for name, data in sources:
        digest.update(name.encode() + b"\0" + data)
    for path in sorted(RUNTIME_ROOT.glob("*.h")) + sorted(WASI_ROOT.rglob("*.h")) + [WASI_ROOT / "freak_v4_wasm_glue.c"]:
        digest.update(str(path.relative_to(RUNTIME_ROOT)).encode() + b"\0" + path.read_bytes())
    out = cache_root / digest.hexdigest()[:16]
    names = [Path(name).stem + ".o" for name, _ in sources] + ["freak_v4_wasm_core.o"]
    objects = [out / name for name in names]
    if all(path.is_file() for path in objects):
        return objects
    staging = out.with_name(out.name + f".tmp{os.getpid()}")
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    core = staging / "freak_v4_wasm_core.c"
    core.write_text(generated, encoding="utf-8")
    include = ["-isystem", str(WASI_ROOT / "include"), f"-I{RUNTIME_ROOT}"]
    for (name, _), obj in zip(sources, names):
        _run([clang, *C_FLAGS, *include, "-c", str(RUNTIME_ROOT / name), "-o", str(staging / obj)],
             f"wasm runtime compile {name}")
    _run([clang, *C_FLAGS, *include, "-c", str(core), "-o", str(staging / "freak_v4_wasm_core.o")],
         "wasm runtime compile (extracted V3 parts)")
    if out.exists():
        shutil.rmtree(staging, ignore_errors=True)
    else:
        staging.replace(out)
    return objects


def link_command(clang: str, module_object: Path, objects: list[Path], output: Path) -> list[str]:
    # --fatal-warnings: a function signature mismatch (a C declaration that
    # disagrees with the runtime's definition) would otherwise link and trap.
    return [clang, f"--target={TRIPLE}", "-nostdlib", "-Wl,--gc-sections", "-Wl,--strip-all", "-Wl,--fatal-warnings",
            f"-Wl,-z,stack-size={STACK_BYTES}", str(module_object), *(str(path) for path in objects),
            "-o", str(output)]


def link(clang: str, llvm_path: Path, output: Path, cache_root: Path) -> None:
    """Compile a V4 module and link it with the wasm runtime into output."""
    objects = runtime_objects(clang, cache_root)
    module_object = llvm_path.with_suffix(".o")
    _run([clang, f"--target={TRIPLE}", "-Oz", "-w", "-c", str(llvm_path), "-o", str(module_object)],
         "wasm module compile")
    _run(link_command(clang, module_object, objects, output), "wasm link")


def linker_error(clang: str) -> str:
    """Why this clang cannot link wasm32 modules, or "" when it can."""
    if not re.search(r"\b(1[89]|[2-9]\d)\.", _clang_identity(clang)):
        return f"wasm32 builds need clang 18 or newer: {_clang_identity(clang)}"
    probe = subprocess.run([clang, f"--target={TRIPLE}", "-print-prog-name=wasm-ld"],
                           capture_output=True, text=True, timeout=30)
    name = probe.stdout.strip() or "wasm-ld"
    if not (Path(name).is_file() or shutil.which(name) or shutil.which("wasm-ld")):
        return "wasm32 builds need wasm-ld (the LLVM lld package)"
    return ""
