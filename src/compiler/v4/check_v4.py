def rel(path: Path) -> str:
    return str(path.relative_to(ROOT)).replace("\\", "/")


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def write_text_if_changed(path: Path, text: str) -> bool:
    if path.exists() and read_text(path) == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def hash_text(*parts: str) -> str:
    digest = hashlib.sha256()
    for part in parts:
        digest.update(part.encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()


def crate_path(name: str) -> Path:
    return CRATES_ROOT / name / "src" / "lib.fk"


def crate_paths() -> list[Path]:
    return [crate_path(name) for name in CRATE_ORDER]


def fixture_paths() -> list[Path]:
    if not TESTS_ROOT.exists():
        return []
    return sorted(TESTS_ROOT.glob("*.fk"))


def check_smoke_inventory(fixtures: list[Path]) -> None:
    fixture_names = [fixture.name for fixture in fixtures]
    smoke_names = [str(smoke["fixture"]) for smoke in EXECUTABLE_SMOKES]

    missing = sorted(name for name in fixture_names if name not in smoke_names)
    extra = sorted(name for name in smoke_names if name not in fixture_names)

    seen: dict[str, int] = {}
    for name in smoke_names:
        seen[name] = seen.get(name, 0) + 1
    duplicates = sorted(name for name, count in seen.items() if count > 1)

    if missing or extra or duplicates:
        if missing:
            for name in missing:
                print(f"smoke inventory missing: {name}")
        if extra:
            for name in extra:
                print(f"smoke inventory extra: {name}")
        if duplicates:
            for name in duplicates:
                print(f"smoke inventory duplicate: {name}")
        raise SystemExit(1)

    print(f"smoke inventory: {len(smoke_names)} fixtures")


def check_crate_boundaries() -> None:
    boundary_crates = sorted(
        {
            *CRATE_BOUNDARY_REQUIRED.keys(),
            *CRATE_BOUNDARY_FORBIDDEN.keys(),
        }
    )
    contents = {name: read_text(crate_path(name)) for name in boundary_crates}
    violations: list[str] = []

    for crate, checks in CRATE_BOUNDARY_REQUIRED.items():
        text = contents[crate]
        for label, needle in checks:
            if needle not in text:
                violations.append(f"boundary missing: {crate} {label}")

    for crate, checks in CRATE_BOUNDARY_FORBIDDEN.items():
        text = contents[crate]
        for label, needle in checks:
            if needle in text:
                violations.append(f"boundary violation: {crate} owns {label}")

    if violations:
        for violation in violations:
            print(violation)
        raise SystemExit(1)

    print(f"boundary rules: {', '.join(boundary_crates)}")


def check_tooling_interfaces() -> None:
    readme = read_text(V4_ROOT / "README.md")
    lsp_source = read_text(crate_path("freak_lsp"))
    violations: list[str] = []

    for marker in README_PROTOCOL_MARKERS:
        if marker not in readme:
            violations.append(f"tooling docs missing: {marker}")

    for method in TOOLING_INTERFACE_ENDPOINTS:
        if "|" + method not in lsp_source and '"' + method + '"' not in lsp_source:
            violations.append(f"tooling endpoint missing: {method}")

    if violations:
        for violation in violations:
            print(violation)
        raise SystemExit(1)

    print(f"tooling interfaces: {len(TOOLING_INTERFACE_ENDPOINTS)} endpoints")


def check_snapshot_inventories() -> None:
    readme = read_text(V4_ROOT / "README.md")
    snapshot_source = read_text(crate_path("freak_snapshot"))
    violations: list[str] = []

    expected_section_count = len(UNIT_SNAPSHOT_SECTIONS)
    if f"sections={expected_section_count}" not in readme:
        violations.append(f"snapshot docs missing: sections={expected_section_count}")

    for section in UNIT_SNAPSHOT_SECTIONS:
        name = section["name"]
        if f'section_name == "{name}"' not in snapshot_source:
            violations.append(f"snapshot section missing: {name}")
        if section["validate"] not in snapshot_source:
            violations.append(f"snapshot validator missing: {name}")
        if section["restore"] not in snapshot_source:
            violations.append(f"snapshot restore missing: {name}")
        if section["endpoint"] not in readme:
            violations.append(f"snapshot docs missing endpoint: {section['endpoint']}")

    for family, public_field in INVALIDATION_FAMILY_FIELDS:
        if f'family == "{family}"' not in snapshot_source:
            violations.append(f"invalidation family missing: {family}")
        if public_field not in snapshot_source:
            violations.append(f"invalidation report field missing: {public_field}")
        if public_field not in readme:
            violations.append(f"invalidation docs missing: {public_field}")

    if violations:
        for violation in violations:
            print(violation)
        raise SystemExit(1)

    print(
        "snapshot inventories: "
        f"sections={len(UNIT_SNAPSHOT_SECTIONS)} "
        f"invalidation-families={len(INVALIDATION_FAMILY_FIELDS)}"
    )


def check_exists(paths: list[Path]) -> None:
    missing = [path for path in paths if not path.exists()]
    if missing:
        for path in missing:
            print(f"missing: {rel(path)}")
        raise SystemExit(1)
    print(f"exists: {len(paths)} files")


def check_ascii(paths: list[Path]) -> None:
    bad: list[Path] = []
    for path in paths:
        try:
            path.read_text(encoding="ascii")
        except UnicodeDecodeError:
            bad.append(path)
    if bad:
        for path in bad:
            print(f"non-ascii: {rel(path)}")
        raise SystemExit(1)
    print(f"ascii: {len(paths)} files")


def parse_source(source: str, label: str):
    try:
        return Parser.from_source(source)
    except Exception as exc:
        print(f"parse failed: {label}")
        print(exc)
        raise SystemExit(1) from exc


def check_individual_parse(paths: list[Path]) -> None:
    for path in paths:
        parse_source(read_text(path), rel(path))
    print(f"parse individual: {len(paths)} files")


def flattened_crates() -> str:
    out: list[str] = []
    for path in crate_paths():
        out.append(f"-- flattened from {rel(path)}\n")
        out.append(read_text(path))
        out.append("\n")
    return "\n".join(out)


def check_flattened_crates() -> str:
    source = flattened_crates()
    program = parse_source(source, "flattened V4 crates")
    diagnostics = TypeChecker().check(program)
    if diagnostics:
        print("typecheck failed: flattened V4 crates")
        for diag in diagnostics[:80]:
            print(diag)
        if len(diagnostics) > 80:
            print(f"... {len(diagnostics) - 80} more diagnostics")
        raise SystemExit(1)
    print(f"flattened crates: statements={len(program.statements)}")
    return source


def fixture_source(base_source: str, fixture: Path) -> str:
    return base_source + "\n\n-- fixture\n" + read_text(fixture)


def transpile_fixture(base_source: str, fixture: Path) -> tuple[str, bool]:
    label = rel(fixture)
    source = fixture_source(base_source, fixture)
    c_source, diagnostics, uses_ui = transpile(source, fixture.with_suffix(".flat.fk"))
    if diagnostics:
        print(f"transpile failed: {label}")
        for diag in diagnostics[:40]:
            print(diag)
        if len(diagnostics) > 40:
            print(f"... {len(diagnostics) - 40} more diagnostics")
        raise SystemExit(1)
    if c_source is None:
        print(f"transpile failed: {label}")
        print("transpile returned no C source")
        raise SystemExit(1)
    return c_source, uses_ui


def check_fixture_transpile(base_source: str, fixtures: list[Path]) -> dict[Path, tuple[str, bool]]:
    artifacts: dict[Path, tuple[str, bool]] = {}
    for fixture in fixtures:
        label = rel(fixture)
        c_source, uses_ui = transpile_fixture(base_source, fixture)
        artifacts[fixture] = (c_source, uses_ui)
        print(f"fixture transpile: {label} c_bytes={len(c_source)} uses_ui={uses_ui}")
    return artifacts


def compile_runtime_smoke(
    clang: str,
    include_arg: str,
    runtime_smoke_c: Path,
    runtime_source: str,
    fixture: Path,
    c_source: str,
) -> tuple[Path, bool]:
    suffix = ".exe" if sys.platform.startswith("win") else ""
    c_path = RUNTIME_BUILD_ROOT / f"{fixture.stem}.fk.c"
    exe_path = RUNTIME_BUILD_ROOT / f"{fixture.stem}{suffix}"
    stamp_path = RUNTIME_BUILD_ROOT / f"{fixture.stem}.compile.sha256"
    compile_key = hash_text(
        "v4-runtime-smoke-v1",
        clang,
        include_arg,
        runtime_source,
        c_source,
    )

    write_text_if_changed(c_path, c_source)
    if exe_path.exists() and stamp_path.exists() and read_text(stamp_path).strip() == compile_key:
        return exe_path, False

    compile_cmd = [
        clang,
        "-o",
        str(exe_path),
        str(c_path),
        str(runtime_smoke_c),
        include_arg,
        "-w",
        "-O0",
    ]
    compiled = subprocess.run(compile_cmd, cwd=ROOT, text=True, capture_output=True)
    if compiled.returncode != 0:
        print(f"runtime compile failed: {rel(fixture)}")
        print(compiled.stdout)
        print(compiled.stderr)
        raise SystemExit(1)

    stamp_path.write_text(compile_key, encoding="utf-8")
    return exe_path, True


def select_smokes(filters: list[str]) -> list[dict[str, object]]:
    if not filters:
        return EXECUTABLE_SMOKES

    lowered = [item.lower() for item in filters]
    selected: list[dict[str, object]] = []
    for smoke in EXECUTABLE_SMOKES:
        haystacks = [
            smoke["name"],
            smoke["fixture"],
            Path(smoke["fixture"]).stem,
        ]
        if any(needle in haystack.lower() for needle in lowered for haystack in haystacks):
            selected.append(smoke)

    if selected:
        return selected

    print("runtime smoke failed: no smoke matched filters")
    for needle in filters:
        print(f"filter: {needle}")
    for smoke in EXECUTABLE_SMOKES:
        print(f"available smoke: {smoke['name']} fixture={smoke['fixture']}")
    raise SystemExit(1)


def check_executable_smokes(
    base_source: str,
    smokes: list[dict[str, object]],
    fixture_artifacts: dict[Path, tuple[str, bool]],
) -> None:
    clang = shutil.which("clang")
    if clang is None:
        print("runtime smoke failed: clang not found")
        raise SystemExit(1)

    RUNTIME_BUILD_ROOT.mkdir(parents=True, exist_ok=True)
    runtime_c = RUNTIME_ROOT / "freak_runtime.c"
    runtime_smoke_c = RUNTIME_BUILD_ROOT / "freak_runtime_v4_smoke.c"
    runtime_source = read_text(runtime_c)
    runtime_source = runtime_source.replace("#define FREAK_MAX_ARRAYS 256", "#define FREAK_MAX_ARRAYS 8192")
    write_text_if_changed(runtime_smoke_c, runtime_source)
    include_arg = f"-I{RUNTIME_ROOT}"

    for smoke in smokes:
        fixture = TESTS_ROOT / str(smoke["fixture"])
        label = rel(fixture)
        artifact = fixture_artifacts.get(fixture)
        if artifact is None:
            artifact = transpile_fixture(base_source, fixture)
            fixture_artifacts[fixture] = artifact
        c_source, uses_ui = artifact
        if uses_ui:
            print(f"runtime smoke failed: {label} unexpectedly requires UI")
            raise SystemExit(1)

        exe_path, compiled = compile_runtime_smoke(
            clang,
            include_arg,
            runtime_smoke_c,
            runtime_source,
            fixture,
            c_source,
        )
        executed = subprocess.run([str(exe_path)], cwd=ROOT, text=True, capture_output=True, timeout=60)
        output = executed.stdout + executed.stderr
        if executed.returncode != 0:
            print(f"runtime execution failed: {label} exit={executed.returncode}")
            print(output[:4000])
            raise SystemExit(1)

        missing = [needle for needle in smoke["expect"] if needle not in output]
        if missing:
            print(f"runtime smoke failed: {label}")
            for needle in missing:
                print(f"missing output: {needle}")
            print(output[:4000])
            raise SystemExit(1)

        compile_mode = "clang" if compiled else "cache"
        print(
            f"runtime smoke: {smoke['name']} fixture={label} "
            f"compile={compile_mode} output_bytes={len(output)}"
        )


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run Maverick (00-unit) V4 bootstrap checks.")
    parser.add_argument(
        "--fast",
        action="store_true",
        help="skip executable runtime smokes and stop after fixture transpiles",
    )
    parser.add_argument(
        "--smoke",
        action="append",
        default=[],
        metavar="NAME",
        help="run only matching executable smoke fixtures by name or fixture stem",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    crates = crate_paths()
    fixtures = fixture_paths()
    all_files = crates + fixtures + [V4_ROOT / "README.md"]
    selected_smokes = select_smokes(args.smoke)
    selected_fixture_set = {TESTS_ROOT / str(smoke["fixture"]) for smoke in selected_smokes}
    transpile_targets = fixtures if not args.smoke else [fixture for fixture in fixtures if fixture in selected_fixture_set]

    print("Maverick (00-unit) checks")
    check_exists(crates)
    check_ascii(all_files)
    check_individual_parse(crates + fixtures)
    check_smoke_inventory(fixtures)
    check_crate_boundaries()
    check_tooling_interfaces()
    check_snapshot_inventories()
    base_source = check_flattened_crates()
    if args.fast and args.smoke:
        print(f"mode: fast smoke filters={len(args.smoke)} fixtures={len(transpile_targets)}")
    elif args.fast:
        print("mode: fast")
    elif args.smoke:
        print(f"mode: targeted smokes={len(selected_smokes)}")

    fixture_artifacts = check_fixture_transpile(base_source, transpile_targets)
    if not args.fast:
        check_executable_smokes(base_source, selected_smokes, fixture_artifacts)
    print("Maverick checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
