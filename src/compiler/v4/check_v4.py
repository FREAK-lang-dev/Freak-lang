def repo_root() -> Path:
    here = Path(__file__).resolve()
    for parent in here.parents:
        if (parent / "freakc").is_dir() and (parent / "src" / "compiler" / "v4").is_dir():
            return parent
    raise RuntimeError("could not locate repository root")


